"use strict";

/**
 * @fileoverview Biocircuit Distribution Build Orchestrator.
 *
 * Packages intermediate build artifacts from build/ into dist/ preserving the
 * exact hierarchy of tokens, styles, and scripts matching the source tokens taxonomy.
 * Emits final index.css and index.js entry points.
 *
 * Distribution Structure
 * ======================
 * dist/
 * ├── index.js                     # Master JS entry point
 * ├── index.d.ts                   # Master TypeScript declaration
 * ├── index.css                    # Master stylesheet (layers, primitives, themes)
 * ├── tokens/                      # Mirror of tokens hierarchy
 * │   ├── primitives/
 * │   │   ├── color.palette.json
 * │   │   └── layout.tokens.json
 * │   └── semantics/
 * │       └── color/
 * │           ├── theme-dark.json
 * │           └── theme-light.json
 * ├── styles/                      # Mirror of styles hierarchy
 * │   ├── primitives/
 * │   │   ├── color.css
 * │   │   └── layout.css
 * │   └── semantics/
 * │       └── color/
 * │           ├── theme-dark.css
 * │           └── theme-light.css
 * └── scripts/                     # Mirror of scripts hierarchy
 *     ├── primitives/
 *     │   ├── color.engine.js (.d.ts)
 *     │   ├── color.tokens.js (.d.ts)
 *     │   ├── layout.engine.js (.d.ts)
 *     │   └── layout.tokens.js (.d.ts)
 *     └── semantics/
 *         └── color/
 *             ├── theme-dark.js (.d.ts)
 *             └── theme-light.js (.d.ts)
 *
 * @module scripts/dist-orchestrator
 * @license GPL-3.0-or-later
 * @author Dwij Bavisi <dwij.bavisi@crabwire.net>
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const BUILD_DIR = path.join(ROOT_DIR, 'build');
const DIST_DIR = path.join(ROOT_DIR, 'dist');

/**
 * Recursively copies a directory tree from source to target.
 *
 * @param {string} src - Source directory path.
 * @param {string} dest - Destination directory path.
 */
function copyDirRecursive(src: string, dest: string): void {
    if (!fs.existsSync(src)) {
        return;
    }

    if (!fs.existsSync(dest)) {
        fs.mkdirSync(dest, { recursive: true });
    }

    const entries = fs.readdirSync(src, { withFileTypes: true });
    for (const entry of entries) {
        const srcPath = path.join(src, entry.name);
        const destPath = path.join(dest, entry.name);

        if (entry.isDirectory()) {
            copyDirRecursive(srcPath, destPath);
        } else {
            fs.copyFileSync(srcPath, destPath);
        }
    }
}

/**
 * Builds the aggregated master stylesheet index.css with dual-theme media-query support.
 */
function buildIndexCss(): void {
    const darkCssPath = path.join(DIST_DIR, 'styles', 'semantics', 'color', 'theme-dark.css');
    let darkVars = '';

    if (fs.existsSync(darkCssPath)) {
        const darkContent = fs.readFileSync(darkCssPath, 'utf-8');
        const match = darkContent.match(/\[data-theme="dark"\]\s*\{([\s\S]*?)\}/);
        if (match) {
            darkVars = match[1].trim();
        }
    }

    const formattedDarkVars = darkVars
        ? darkVars
              .split('\n')
              .map(line => `            ${line.trim()}`)
              .filter(Boolean)
              .join('\n')
        : '';

    const indexCssContent = `/**
 * @crabwire/bloatware-biocircuit
 * An over-engineered Web UI library
 *
 * Master Design System Stylesheet Entry Point.
 * Auto-generated by scripts/dist-orchestrator.ts. DO NOT EDIT MANUALLY.
 */

@layer biocircuit.tokens, biocircuit.layout, biocircuit.theme;

@import './styles/primitives/color.css' layer(biocircuit.tokens);
@import './styles/primitives/layout.css';
@import './styles/semantics/color/theme-light.css' layer(biocircuit.theme);
@import './styles/semantics/color/theme-dark.css' layer(biocircuit.theme);

/* Default dark theme activation via system preference when no explicit light theme override */
@layer biocircuit.theme {
    @media (prefers-color-scheme: dark) {
        :root:not([data-theme="light"]) {
${formattedDarkVars}
        }
    }
}
`;

    const outPath = path.join(DIST_DIR, 'index.css');
    fs.writeFileSync(outPath, indexCssContent, 'utf-8');
    console.log('[dist] Generated: dist/index.css');
}

/**
 * Builds master index.js and index.d.ts entry points.
 */
function buildIndexJs(): void {
    const indexJsContent = `"use strict";

/**
 * @fileoverview Biocircuit Design System Master Entry Point.
 *
 * Re-exports host-agnostic layout and color primitive engines, configuration contracts,
 * design token schemas, and semantic themes.
 *
 * @module @crabwire/bloatware-biocircuit
 * @license GPL-3.0-or-later
 * @author Dwij Bavisi <dwij.bavisi@crabwire.net>
 */

// Primitives Subsystem (Engines, Token Schemas, Constants)
export * from './scripts/primitives/color.engine.js';
export * from './scripts/primitives/color.tokens.js';
export * from './scripts/primitives/layout.engine.js';
export * from './scripts/primitives/layout.tokens.js';

// Semantics Subsystem (Themes: Dark & Light JS Tokens)
export * as themeDark from './scripts/semantics/color/theme-dark.js';
export * as themeLight from './scripts/semantics/color/theme-light.js';
`;

    const indexDtsContent = `/**
 * @fileoverview Biocircuit Design System Master Declarations.
 *
 * @module @crabwire/bloatware-biocircuit
 */

export * from './scripts/primitives/color.engine.js';
export * from './scripts/primitives/color.tokens.js';
export * from './scripts/primitives/layout.engine.js';
export * from './scripts/primitives/layout.tokens.js';

export * as themeDark from './scripts/semantics/color/theme-dark.js';
export * as themeLight from './scripts/semantics/color/theme-light.js';
`;

    fs.writeFileSync(path.join(DIST_DIR, 'index.js'), indexJsContent, 'utf-8');
    fs.writeFileSync(path.join(DIST_DIR, 'index.d.ts'), indexDtsContent, 'utf-8');
    console.log('[dist] Generated: dist/index.js & dist/index.d.ts');
}

/**
 * Main distribution orchestration procedure.
 */
export async function runDistOrchestrator(): Promise<void> {
    const startTime = performance.now();
    console.log('[dist] Biocircuit Distribution Orchestrator starting...');

    if (!fs.existsSync(BUILD_DIR)) {
        throw new Error('[dist] build/ directory does not exist. Run "npm run build:intermediate" first.');
    }

    if (!fs.existsSync(DIST_DIR)) {
        fs.mkdirSync(DIST_DIR, { recursive: true });
    }

    // 1. Copy Tokens hierarchy
    console.log('  [1/4] Copying tokens hierarchy (primitives & semantics)...');
    copyDirRecursive(path.join(BUILD_DIR, 'tokens'), path.join(DIST_DIR, 'tokens'));

    // 2. Copy Styles hierarchy
    console.log('  [2/4] Copying styles hierarchy (primitives & semantics)...');
    copyDirRecursive(path.join(BUILD_DIR, 'styles'), path.join(DIST_DIR, 'styles'));

    // 3. Copy Scripts hierarchy
    console.log('  [3/4] Copying scripts hierarchy (primitives & semantics)...');
    copyDirRecursive(path.join(BUILD_DIR, 'scripts'), path.join(DIST_DIR, 'scripts'));

    // 4. Synthesize Entry Points
    console.log('  [4/4] Synthesizing index.css, index.js, and index.d.ts...');
    buildIndexCss();
    buildIndexJs();

    const durationMs = Math.round(performance.now() - startTime);
    console.log(`[dist] Distribution build completed successfully in ${durationMs}ms!`);
}

// Direct execution guard
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
    runDistOrchestrator().catch(err => {
        console.error('[dist] Distribution orchestration failed:', err);
        process.exit(1);
    });
}

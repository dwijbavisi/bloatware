import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { createLayoutEngine } from '../../src/scripts/layout.engine.js';
import { DEFAULT_LAYOUT_CONFIG } from '../../src/scripts/layout.tokens.js';
import { CssDocumentBuilder } from '../common/emitters.css.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..', '..');
const OUTPUT_FILE = path.join(ROOT_DIR, 'build', 'styles', 'layout.css');

/**
 * Constructs the complete CSS AST document for the layout subsystem.
 *
 * Notes
 * -----
 * Instantiates the pure layout engine using DEFAULT_LAYOUT_CONFIG, constructs
 * cascade layers for tokens and layout rules, and returns the configured
 * CssDocumentBuilder.
 *
 * Returns
 * -------
 * @returns {CssDocumentBuilder}
 *   Configured builder containing the complete layout CSS AST.
 *
 * Examples
 * --------
 * ```ts
 * const builder = buildLayoutCssDocument();
 * const css = builder.serialize();
 * ```
 */
export function buildLayoutCssDocument(): CssDocumentBuilder {
    const engine = createLayoutEngine(DEFAULT_LAYOUT_CONFIG);
    const [baseTier, ...higherTiers] = engine.tiers;

    const builder = new CssDocumentBuilder();

    builder
        .setHeader(`@crabwire/bloatware-biocircuit
An over-engineered Web UI library

Layout Engine Subsystem Stylesheet.
Auto-generated by scripts/emitters/layout.css.ts. DO NOT EDIT MANUALLY.`)
        .setLayerOrder(['biocircuit.tokens', 'biocircuit.layout']);

    // 1. Build biocircuit.tokens layer
    const tokenLayerNodes = [
        CssDocumentBuilder.createRule(
            ':root',
            [
                { property: '--cwbwbc-layout-board-width', value: '100vw' },
                { property: '--cwbwbc-layout-lanes', value: baseTier.lanes },
                { property: '--cwbwbc-layout-k', value: baseTier.k },
                { property: '--cwbwbc-layout-divisor', value: baseTier.divisor },
                { property: '--cwbwbc-layout-keepout', value: 'calc(var(--cwbwbc-layout-board-width) / var(--cwbwbc-layout-divisor))' },
                { property: '--cwbwbc-layout-trace', value: `calc(${engine.config.traceToKeepoutRatio} * var(--cwbwbc-layout-keepout))` },
                { property: '--cwbwbc-layout-clearance', value: 'calc(var(--cwbwbc-layout-k) * var(--cwbwbc-layout-keepout))' },
                { property: '--cwbwbc-layout-active-width', value: 'calc(var(--cwbwbc-layout-board-width) - (2 * var(--cwbwbc-layout-clearance)))' }
            ],
            `${baseTier.name} Baseline (< ${higherTiers[0]?.minWidthCh ?? 65}ch)`
        ),
        ...higherTiers.map(tier =>
            CssDocumentBuilder.createAtRule(
                'media',
                `(min-width: ${tier.minWidthCh}ch)`,
                [
                    CssDocumentBuilder.createRule(
                        ':root',
                        [
                            { property: '--cwbwbc-layout-lanes', value: tier.lanes },
                            { property: '--cwbwbc-layout-k', value: tier.k },
                            { property: '--cwbwbc-layout-divisor', value: tier.divisor }
                        ],
                        `${tier.name} (>= ${tier.minWidthCh}ch)`
                    )
                ]
            )
        )
    ];

    builder.addLayer('biocircuit.tokens', tokenLayerNodes);

    // 2. Build biocircuit.layout layer
    const layoutLayerNodes = [
        CssDocumentBuilder.createRule('.cwbwbc-board', [
            { property: 'box-sizing', value: 'border-box' },
            { property: 'width', value: '100%' },
            { property: 'padding-inline', value: 'var(--cwbwbc-layout-clearance)' }
        ]),
        CssDocumentBuilder.createRule('.cwbwbc-grid', [
            { property: 'display', value: 'grid' },
            { property: 'box-sizing', value: 'border-box' },
            { property: 'grid-template-columns', value: 'repeat(var(--cwbwbc-layout-lanes), 1fr)' },
            { property: 'gap', value: 'var(--cwbwbc-layout-keepout)' }
        ])
    ];

    builder.addLayer('biocircuit.layout', layoutLayerNodes);

    return builder;
}

/**
 * Writes the layout stylesheet to disk at build/styles/layout.css using
 * CssDocumentBuilder.writeBuildOutput.
 *
 * Returns
 * -------
 * @returns {void}
 */
export function writeLayoutCss(): void {
    const builder = buildLayoutCssDocument();
    builder.writeBuildOutput(OUTPUT_FILE, ROOT_DIR);
}

// Direct execution guard
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
    writeLayoutCss();
}
